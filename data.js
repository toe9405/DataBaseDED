// รายการหน่วยงานเต็มรูปแบบสำหรับ Auto-complete และ Dropdown
function getAllEnergyDepartments() {
  const list = [];
  ENERGY_DEPT_STRUCTURE.forEach(item => {
    if (item.sections.length === 1 && item.sections[0] === item.division) {
      list.push(item.division);
    } else {
      item.sections.forEach(sec => {
        list.push(`${item.division} (${sec})`);
      });
    }
  });
  return list;
}

