// Helper Functions สำหรับค้นหาและจับคู่ข้อมูล
function getRanksByBranch(branch) {
  return RANK_HIERARCHY[branch] || [];
}

function getRankTier(rankName, branch) {
  const branchRanks = RANK_HIERARCHY[branch] || [];
  const found = branchRanks.find(r => r.rank === rankName);
  if (found) return found.tier;

  for (const b in RANK_HIERARCHY) {
    const f = RANK_HIERARCHY[b].find(r => r.rank === rankName);
    if (f) return f.tier;
  }
  return 99;
}
